// Builds the static Quran data files used by the app (run with: node scripts/build-data.mjs)
// Source: api.alquran.cloud (Tanzil Uthmani + Simple Clean texts)
import { writeFile, mkdir } from 'node:fs/promises';

const API = 'https://api.alquran.cloud/v1/quran/';
const get = async (ed) => (await (await fetch(API + ed)).json()).data.surahs;

const NAMES = ['الفاتحة','البقرة','آل عمران','النساء','المائدة','الأنعام','الأعراف','الأنفال','التوبة','يونس','هود','يوسف','الرعد','إبراهيم','الحجر','النحل','الإسراء','الكهف','مريم','طه','الأنبياء','الحج','المؤمنون','النور','الفرقان','الشعراء','النمل','القصص','العنكبوت','الروم','لقمان','السجدة','الأحزاب','سبأ','فاطر','يس','الصافات','ص','الزمر','غافر','فصلت','الشورى','الزخرف','الدخان','الجاثية','الأحقاف','محمد','الفتح','الحجرات','ق','الذاريات','الطور','النجم','القمر','الرحمن','الواقعة','الحديد','المجادلة','الحشر','الممتحنة','الصف','الجمعة','المنافقون','التغابن','الطلاق','التحريم','الملك','القلم','الحاقة','المعارج','نوح','الجن','المزمل','المدثر','القيامة','الإنسان','المرسلات','النبأ','النازعات','عبس','التكوير','الانفطار','المطففين','الانشقاق','البروج','الطارق','الأعلى','الغاشية','الفجر','البلد','الشمس','الليل','الضحى','الشرح','التين','العلق','القدر','البينة','الزلزلة','العاديات','القارعة','التكاثر','العصر','الهمزة','الفيل','قريش','الماعون','الكوثر','الكافرون','النصر','المسد','الإخلاص','الفلق','الناس'];

const norm = (t) => t
  .replace(/[ً-ٰٟۖ-ۭـ]/g, '')
  .replace(/[ٱأإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه').replace(/ؤ/g, 'و').replace(/ئ/g, 'ي')
  .replace(/\s+/g, ' ').trim();

// Drop the leading basmala (first 4 words) that the API prepends to the first ayah
const stripBasmala = (t) => { const w = t.split(' '); return norm(w.slice(0, 4).join(' ')) === 'بسم الله الرحمن الرحيم' ? w.slice(4).join(' ') : t; };

const [uth, clean] = await Promise.all([get('quran-uthmani'), get('quran-simple-clean')]);

const texts = [], search = [], surahs = [], juz = [], hizb = [], pages = [], sajda = {};
let g = 0, lastJ = 0, lastH = 0, lastP = 0;
uth.forEach((s, si) => {
  // Sanity check our clean names against the API names
  const apiName = norm(s.name.replace(/^سُورَةُ\s*/, ''));
  if (apiName !== norm(NAMES[si])) console.warn('name check', si + 1, apiName, NAMES[si]);
  surahs.push([NAMES[si], s.revelationType === 'Meccan' ? 'M' : 'D', s.ayahs.length, g]);
  s.ayahs.forEach((a, ai) => {
    let t = a.text.replace(/^﻿/, '');
    let c = clean[si].ayahs[ai].text.replace(/^﻿/, '');
    if (ai === 0 && si !== 0 && si !== 8) {
      const before = t;
      t = stripBasmala(t);
      c = stripBasmala(c);
      if (t === before) console.warn('no basmala stripped', si + 1);
    }
    texts.push(t.trim());
    search.push(norm(c));
    if (a.juz !== lastJ) { juz.push(g); lastJ = a.juz; }
    if (a.hizbQuarter !== lastH) { hizb.push(g); lastH = a.hizbQuarter; }
    if (a.page !== lastP) { pages.push(g); lastP = a.page; }
    if (a.sajda) sajda[g] = a.sajda.obligatory ? 2 : 1;
    g++;
  });
});

console.log({ ayahs: g, juz: juz.length, hizbQuarters: hizb.length, pages: pages.length, sajda: Object.keys(sajda).length });

await mkdir('data', { recursive: true });
await writeFile('data/quran.json', JSON.stringify(texts));
await writeFile('data/search.json', JSON.stringify(search));
await writeFile('js/meta.js',
`// Generated by scripts/build-data.mjs — do not edit by hand.
// SURAHS: [name, type (M = Meccan, D = Medinan), ayah count, first global ayah index]
export const SURAHS = ${JSON.stringify(surahs)};
// First global ayah index (0-based) of each juz, hizb quarter and mushaf page
export const JUZ = ${JSON.stringify(juz)};
export const HIZB = ${JSON.stringify(hizb)};
export const PAGES = ${JSON.stringify(pages)};
// Sajda ayahs: global index -> 1 recommended, 2 obligatory
export const SAJDA = ${JSON.stringify(sajda)};
export const TOTAL_AYAHS = ${g};
`);
